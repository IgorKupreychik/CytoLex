using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using CytoLex.Core.Tests.KbExamples;

namespace CytoLex.Core.Tests.Translation;

/// <summary>
/// Opt-in (T-057): writes a skeleton of the translation golden file for the book examples of ch. 4, 8 and 9 to
/// <c>build/review/translation/golden-draft-2016.yaml</c>: input, cite, fragment flag, the item spans and KB refs the
/// binder gives, and empty summary/sentences to fill in by hand; plus non-book strings from the file named by
/// <c>CYTOLEX_GOLDEN_DRAFT_INPUTS</c> (origin synthetic). Strings already in <c>golden.yaml</c> are left out.
/// Run with the environment variable <c>CYTOLEX_GOLDEN_DRAFT=1</c>; skips otherwise.
/// </summary>
public class GoldenDraftTests
{
    public const string RelativePath = "build/review/translation/golden-draft-2016.yaml";

    private static readonly string[] _chapters = ["ch04/", "ch08/", "ch09/"];

    private static readonly JsonSerializerOptions _json = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    [Fact]
    public void WriteGoldenDraft()
    {
        if (Environment.GetEnvironmentVariable("CYTOLEX_GOLDEN_DRAFT") != "1")
        {
            Assert.Skip("opt-in: set CYTOLEX_GOLDEN_DRAFT=1 to write " + RelativePath);
        }

        var sb = new StringBuilder();
        sb.Append("# Skeleton of kb/translation/2016/golden.yaml (T-057); generated by GoldenDraftTests, do not edit.\n");
        sb.Append("version: \"2016\"\ngolden:\n");
        var skipped = new List<string>();
        foreach (var (text, cite) in BookExamples().Concat(ExtraInputs()))
        {
            if (GoldenFile.Entries2016.ContainsKey(text))
            {
                continue;
            }

            var fragment = KbCatalog.IsFragment(text);
            var model = GoldenFile.Model(text, fragment);
            if (model is null || model.IsPartial)
            {
                skipped.Add(text);
                continue;
            }

            sb.Append(CultureInfo.InvariantCulture, $"  - input: {Q(text)}\n");
            sb.Append(cite is null ? "    origin: synthetic\n" : $"    cite: {cite}\n");
            if (fragment)
            {
                sb.Append("    fragment: true\n");
            }

            var items = GoldenFile.Items(model).ToList();
            sb.Append("    context: unknown\n    summary: \"\"\n");
            sb.Append(items.Count == 0 ? "    items: []\n" : "    items:\n");
            foreach (var (span, nodes) in items)
            {
                var spanText = text.Substring(span.Start, span.Length);
                var refs = string.Join(", ", GoldenFile.Refs(nodes).Select(Q));
                sb.Append(CultureInfo.InvariantCulture, $"      - span: {{start: {span.Start}, text: {Q(spanText)}}}\n");
                sb.Append("        sentence: \"\"\n");
                sb.Append(CultureInfo.InvariantCulture, $"        kb: [{refs}]\n");
            }

            sb.Append("    review: {checked: false}\n");
        }

        foreach (var s in skipped)
        {
            sb.Append(CultureInfo.InvariantCulture, $"# not a single karyotype segment, or with syntax errors: {Q(s)}\n");
        }

        var path = Path.Combine(RuleCoverageReport.RepoRoot(), RelativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>
    /// Non-book strings (origin synthetic) from the file named by <c>CYTOLEX_GOLDEN_DRAFT_INPUTS</c>, one per line;
    /// none without it.
    /// </summary>
    private static List<(string Text, string? Cite)> ExtraInputs()
    {
        var path = Environment.GetEnvironmentVariable("CYTOLEX_GOLDEN_DRAFT_INPUTS");
        return string.IsNullOrEmpty(path)
            ? []
            : [.. File.ReadAllLines(path).Select(l => l.Trim()).Where(l => l.Length > 0).Select(l => (l, (string?)null))];
    }

    /// <summary>The cited valid examples of ch. 4, 8 and 9, first occurrence of each string, with the cite as flow YAML.</summary>
    private static List<(string Text, string? Cite)> BookExamples()
    {
        using var stream = typeof(KbCatalog).Assembly.GetManifestResourceStream(KbCatalog.ResourceName)!;
        using var doc = JsonDocument.Parse(stream);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var result = new List<(string, string?)>();
        foreach (var rule in doc.RootElement.GetProperty("editions").GetProperty("2016").GetProperty("rules").EnumerateArray())
        {
            var file = rule.GetProperty("file").GetString()!;
            if (!_chapters.Any(c => file.StartsWith(c, StringComparison.Ordinal))
                || !rule.GetProperty("examples").TryGetProperty("valid", out var valid))
            {
                continue;
            }

            foreach (var ex in valid.EnumerateArray())
            {
                var text = ex.GetProperty("text").GetString()!;
                if (!ex.TryGetProperty("cite", out var c) || !seen.Add(text))
                {
                    continue;
                }

                var parts = new List<string>
                {
                    "section: " + Q(c.GetProperty("section").GetString()!),
                    "page: " + c.GetProperty("page").GetInt32().ToString(CultureInfo.InvariantCulture),
                };
                foreach (var anchor in new[] { "para", "example", "float" })
                {
                    if (c.TryGetProperty(anchor, out var a))
                    {
                        parts.Add($"{anchor}: {Q(a.GetString()!)}");
                    }
                }

                result.Add((text, "{" + string.Join(", ", parts) + "}"));
            }
        }

        return result;
    }

    private static string Q(string s) => JsonSerializer.Serialize(s, _json);
}
