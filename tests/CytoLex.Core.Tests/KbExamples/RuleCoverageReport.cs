using System.Globalization;
using System.Reflection;
using System.Text;
using CytoLex.Core.Syntax;
using CytoLex.Core.Validation;

namespace CytoLex.Core.Tests.KbExamples;

/// <summary>
/// The rule coverage report (T-025): per edition, which KB rules have an implementation and examples.
/// Written to <c>build/review/rule-coverage.md</c> by <see cref="RuleCoverageReportTests"/> on every <c>dotnet test</c>.
/// Deterministic (no timestamps), so re-runs give identical files.
/// </summary>
internal static class RuleCoverageReport
{
    public const string RelativePath = "build/review/rule-coverage.md";

    /// <summary><c>[KbRule]</c> IDs that exist in no edition of the KB (core.md §7.2 startup check).</summary>
    public static IReadOnlyList<string> OrphanRuleIds(KbCatalog kb, RuleImplementationScan scan)
    {
        var known = kb.Rules.Select(r => r.Id).ToHashSet(StringComparer.Ordinal);
        return [.. scan.AllRuleIds.Where(id => !known.Contains(id))];
    }

    public static string Build(KbCatalog kb, RuleImplementationScan scan)
    {
        var sb = new StringBuilder();
        Line(sb, "# Rule coverage");
        Line(sb);
        Line(sb, "Generated by `dotnet test` (`RuleCoverageReportTests`, T-025) from `build/kb.json`, the `[KbRule]` implementations in `CytoLex.Core` and the rules the parser reports (T-028 coverage list).");
        Line(sb, "Parser = the parser reports syntax errors for (a surface part of) the rule; only a `[KbRule]` check counts as implemented.");
        Line(sb, "Example cases: one per valid example, one per invalid example, one per `corrected` form. Fragment = a book fragment (abnormality, symbol, or `…` string), checked only for its own rule.");
        Line(sb);

        var orphans = OrphanRuleIds(kb, scan);
        if (orphans.Count > 0)
        {
            Line(sb, "## ⚠ `[KbRule]` IDs not in the KB");
            Line(sb);
            foreach (var id in orphans)
            {
                Line(sb, $"- `{id}`");
            }

            Line(sb);
        }

        foreach (var edition in kb.Editions)
        {
            var rules = kb.Rules.Where(r => r.Edition == edition).ToList();
            var cases = kb.Cases.Where(c => c.Rule.Edition == edition).ToList();
            bool Implemented(KbRuleInfo r) => scan.IsImplemented(edition, r.Id);
            var parser = Validator.Default.Coverage(edition)?.ParserRuleIds ?? [];
            static bool NoExamples(KbRuleInfo r) => r.ValidCount + r.InvalidCount == 0;

            Line(sb, $"## ISCN {edition}");
            Line(sb);
            Line(sb, "| | Count |");
            Line(sb, "|---|---|");
            Line(sb, $"| Rules | {rules.Count} |");
            Line(sb, $"| Implemented | {rules.Count(Implemented)} |");
            Line(sb, $"| No implementation | {rules.Count(r => !Implemented(r))} |");
            Line(sb, $"| Reported by the parser | {rules.Count(r => parser.Contains(r.Id))} |");
            Line(sb, $"| No examples | {rules.Count(NoExamples)} |");
            Line(sb, $"| No invalid example | {rules.Count(r => r.InvalidCount == 0)} |");
            Line(sb, $"| `needs_review` | {rules.Count(r => r.NeedsReview)} |");
            foreach (var kind in Enum.GetValues<ExampleKind>())
            {
                var ofKind = cases.Where(c => c.Kind == kind).ToList();
                Line(sb, $"| {kind} cases (fragments) | {ofKind.Count} ({ofKind.Count(c => c.IsFragment)}) |");
            }

            Line(sb);
            Line(sb, "### Rules");
            Line(sb);
            Line(sb, "| Rule | § | Applies to | Context | Severity | Impl. | Parser | Valid | Invalid | Corrected | Fix | Review |");
            Line(sb, "|---|---|---|---|---|---|---|---|---|---|---|---|");
            foreach (var r in rules)
            {
                var impl = scan.Implementations(edition, r.Id);
                var fix = r.FixLevel is { } level ? (r.FixKind is { } kind ? $"{level} {kind}" : $"{level}") : "–";
                Line(sb, $"| `{r.Id}` | {r.Section} | {string.Join(", ", r.AppliesTo)} | {(r.Context.Count == 0 ? "–" : string.Join(", ", r.Context))} | {r.Severity.ToString().ToLowerInvariant()} | {(impl.Count == 0 ? "–" : "✔ " + string.Join(", ", impl))} | {(parser.Contains(r.Id) ? "✔" : "–")} | {r.ValidCount} | {r.InvalidCount} | {r.CorrectedCount} | {fix} | {(r.NeedsReview ? "needs_review" : "")} |");
            }

            Line(sb);
            ListSection(sb, "No implementation", rules.Where(r => !Implemented(r)));
            ListSection(sb, "No examples", rules.Where(NoExamples));
        }

        Line(sb, "## Core codes");
        Line(sb);
        Line(sb, "Not KB rules (docs/design/core.md §8.4); no citation.");
        Line(sb);
        Line(sb, $"- `{CoreCodes.Unparsed}` (error): text the parser could not attribute to a KB rule; a test failure on any KB example.");
        Line(sb, $"- `{CoreCodes.ContextConflict}` (info): context markers contradict, so the sample context is unknown (T-028).");
        return sb.ToString();
    }

    /// <summary>Writes the report under the repo root and returns its full path.</summary>
    public static string Write(KbCatalog kb, RuleImplementationScan scan)
    {
        var path = Path.Combine(RepoRoot(), RelativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Build(kb, scan), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        return path;
    }

    public static string RepoRoot() =>
        typeof(RuleCoverageReport).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
            .FirstOrDefault(a => a.Key == "RepoRoot")?.Value
        ?? throw new InvalidOperationException("Assembly metadata 'RepoRoot' is missing (set in CytoLex.Core.Tests.csproj).");

    private static void ListSection(StringBuilder sb, string title, IEnumerable<KbRuleInfo> rules)
    {
        var list = rules.ToList();
        Line(sb, string.Create(CultureInfo.InvariantCulture, $"### {title} ({list.Count})"));
        Line(sb);
        foreach (var r in list)
        {
            Line(sb, $"- `{r.Id}` (§{r.Section}, `{r.File}`)");
        }

        if (list.Count == 0)
        {
            Line(sb, "None.");
        }

        Line(sb);
    }

    private static void Line(StringBuilder sb, string text = "") => sb.Append(text).Append('\n');
}
