using System.Globalization;
using System.Text;

namespace CytoLex.External.Comparison;

/// <summary>
/// The comparison report files (T-051): Markdown summary, per-string CSV, a triage draft of the untriaged
/// disagreements and a KB-example draft of the confirmed triage entries. Deterministic, LF line endings.
/// </summary>
public static class ComparisonReport
{
    /// <summary>The CSV columns, in order.</summary>
    public static IReadOnlyList<string> CsvColumns { get; } =
    [
        "id", "iscn", "sent", "agreement", "cytolex_valid", "cytolex_complete", "cytolex_errors", "cytolex_notes", "checker_status",
        "checker_valid", "reason", "triage_label", "triage_confirmed", "suggested_label",
    ];

    /// <summary>The file names <see cref="WriteAll"/> writes for a checker and edition.</summary>
    public static (string Markdown, string Csv, string TriageDraft, string KbDraft) FileNames(string checker, string edition)
    {
        var stem = checker.ToLowerInvariant() + "-" + edition;
        return (stem + ".md", stem + ".csv", stem + "-triage-draft.yaml", stem + "-kb-examples-draft.yaml");
    }

    /// <summary>Writes all four files into <paramref name="directory"/> and returns their paths.</summary>
    public static IReadOnlyList<string> WriteAll(string directory, ComparisonResult result, TriageFile triage)
    {
        ArgumentNullException.ThrowIfNull(result);
        ArgumentNullException.ThrowIfNull(triage);
        Directory.CreateDirectory(directory);
        var names = FileNames(result.Checker, result.Edition);
        var files = new (string Name, string Text)[]
        {
            (names.Markdown, Markdown(result)),
            (names.Csv, Csv(result)),
            (names.TriageDraft, TriageDraft(result)),
            (names.KbDraft, KbExampleDraft(triage)),
        };
        var paths = new List<string>();
        foreach (var (name, text) in files)
        {
            var path = Path.Combine(directory, name);
            File.WriteAllBytes(path, new UTF8Encoding(false).GetBytes(text));
            paths.Add(path);
        }

        return paths;
    }

    /// <summary>The Markdown summary: matrix, strings kept out of it, disagreements with their triage, stale entries.</summary>
    public static string Markdown(ComparisonResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var c = result.Checker;
        var m = result.Matrix;
        var sb = new StringBuilder();
        Line(sb, $"# CytoLex vs. {c} — ISCN {result.Edition}");
        Line(sb);
        Line(sb, "Generated by the comparison engine (T-051; `CytoGpsComparisonReportTests`). Verdicts only: CytoLex valid = no errors in");
        Line(sb, $"ISCN {result.Edition}; {c} valid = accepted (for CytoGPS also after its own repair). Strings {c} can't read are kept out of");
        Line(sb, "the matrix. Triage labels come from the committed triage file (`curated/comparison/`).");
        Line(sb);
        Line(sb, $"- {c}: {StatusText(result)}");
        Line(sb, result.AutoCorrect
            ? $"- CytoLex: with autocorrection (T-096): valid after autocorrection counts as valid ({result.Items.Count(i => i.CytoLexAutoCorrected)} strings); {c} gets the strings as written"
            : "- CytoLex: as written (no autocorrection)");
        Line(sb, $"- Strings: {m.Total} (compared {m.Compared}, not supported by {c} {m.NotSupported}, not compared {m.NotCompared})");
        Line(sb);
        Line(sb, $"## Agreement matrix ({m.Compared} strings)");
        Line(sb);
        Line(sb, $"| | {c} valid | {c} invalid |");
        Line(sb, "|---|---:|---:|");
        Line(sb, $"| **CytoLex valid** | {m.BothValid} | {m.OnlyCheckerInvalid} |");
        Line(sb, $"| **CytoLex invalid** | {m.OnlyCytoLexInvalid} | {m.BothInvalid} |");
        Line(sb);
        Line(sb, $"Agreement: {m.Agreeing} of {m.Compared} ({Percent(m.Agreeing, m.Compared)}).");
        Line(sb);

        var outside = result.Items
            .Where(i => i.Agreement is Agreement.NotSupported or Agreement.NotCompared)
            .GroupBy(i => (i.Agreement, i.Reason))
            .OrderBy(g => g.Key.Agreement).ThenByDescending(g => g.Count()).ThenBy(g => g.Key.Reason, StringComparer.Ordinal)
            .ToList();
        if (outside.Count > 0)
        {
            Line(sb, "## Not in the matrix");
            Line(sb);
            Line(sb, "| Kind | Reason | Strings |");
            Line(sb, "|---|---|---:|");
            foreach (var g in outside)
            {
                var kind = g.Key.Agreement == Agreement.NotSupported ? $"not supported by {c}" : "not compared";
                Line(sb, $"| {kind} | {Cell(g.Key.Reason ?? "")} | {g.Count()} |");
            }

            Line(sb);
        }

        var onlyCytoLex = result.Items.Where(i => i.Agreement == Agreement.OnlyCytoLexInvalid).ToList();
        var onlyChecker = result.Items.Where(i => i.Agreement == Agreement.OnlyCheckerInvalid).ToList();
        Line(sb, "## Disagreements");
        Line(sb);
        Line(sb, $"### CytoLex invalid, {c} valid ({onlyCytoLex.Count})");
        Line(sb);
        if (onlyCytoLex.Count == 0)
        {
            Line(sb, "None.");
            Line(sb);
        }

        foreach (var g in onlyCytoLex.GroupBy(i => i.CytoLexErrors.FirstOrDefault() ?? "(no error rule)")
                     .OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            Line(sb, $"#### {g.Key} ({g.Count()})");
            Line(sb);
            Line(sb, "| Id | String | CytoLex errors | Triage |");
            Line(sb, "|---|---|---|---|");
            foreach (var i in g)
            {
                Line(sb, $"| {Cell(i.Item.Id ?? i.Item.Line.ToString(CultureInfo.InvariantCulture))} | {Code(i.Item.Input)} | {Cell(string.Join(", ", i.CytoLexErrors))} | {TriageText(i)} |");
            }

            Line(sb);
        }

        Line(sb, $"### {c} invalid, CytoLex valid ({onlyChecker.Count})");
        Line(sb);
        if (onlyChecker.Count == 0)
        {
            Line(sb, "None.");
            Line(sb);
        }

        foreach (var g in onlyChecker.GroupBy(i => i.External.ToolStatus)
                     .OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            Line(sb, $"#### {Cell(g.Key)} ({g.Count()})");
            Line(sb);
            Line(sb, $"| Id | String as sent | {c} message | CytoLex warnings/infos | Triage |");
            Line(sb, "|---|---|---|---|---|");
            foreach (var i in g)
            {
                var message = i.External.Messages.FirstOrDefault()?.Text ?? "";
                Line(sb, $"| {Cell(i.Item.Id ?? i.Item.Line.ToString(CultureInfo.InvariantCulture))} | {Code(i.External.SentInput)} | {Cell(Shorten(message))} | {Cell(string.Join(", ", i.CytoLexNotes))} | {TriageText(i)} |");
            }

            Line(sb);
        }

        var disagreements = result.Items.Where(i => i.IsDisagreement).ToList();
        var untriaged = disagreements.Where(i => i.Triage is null).ToList();
        Line(sb, "## Triage");
        Line(sb);
        Line(sb, $"- Triaged: {disagreements.Count - untriaged.Count} of {disagreements.Count} disagreements"
            + $" ({disagreements.Count(i => i.Triage is { Confirmed: true })} confirmed).");
        Line(sb, $"- Untriaged: {untriaged.Count} ({untriaged.Count(i => i.SuggestedLabel is not null)} with a suggested label);"
            + $" draft: `{FileNames(c, result.Edition).TriageDraft}`.");
        Line(sb, $"- Stale entries (no longer a disagreement in this batch): {result.StaleTriage.Length}.");
        foreach (var e in result.StaleTriage)
        {
            Line(sb, $"  - line {e.Line}: {Code(e.Iscn)} ({TriageFile.LabelName(e.Label)})");
        }

        return sb.ToString();
    }

    /// <summary>One CSV row per string (<see cref="CsvColumns"/>).</summary>
    public static string Csv(ComparisonResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var sb = new StringBuilder();
        CsvRow(sb, CsvColumns);
        foreach (var i in result.Items)
        {
            CsvRow(sb,
            [
                i.Item.Id ?? "",
                i.Item.Input,
                i.External.SentInput,
                AgreementName(i.Agreement),
                i.CytoLexValid is { } v ? Bool(v) : "",
                Bool(i.CytoLexComplete),
                string.Join(' ', i.CytoLexErrors),
                string.Join(' ', i.CytoLexNotes),
                i.External.ToolStatus,
                i.External.Verdict switch { ExternalVerdict.Valid => "true", ExternalVerdict.Invalid => "false", _ => "" },
                i.Reason ?? "",
                i.Triage is { } t ? TriageFile.LabelName(t.Label) : "",
                i.Triage is { } t2 ? Bool(t2.Confirmed) : "",
                i.SuggestedLabel is { } s ? TriageFile.LabelName(s) : "",
            ]);
        }

        return sb.ToString();
    }

    /// <summary>
    /// The untriaged disagreements as triage entries (one per string), with the suggested label or <c>TODO</c> and
    /// <c>confirmed: false</c>, to merge into the triage file after review.
    /// </summary>
    public static string TriageDraft(ComparisonResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var sb = new StringBuilder();
        Line(sb, "# Draft triage entries: the untriaged disagreements of the last comparison run (T-051).");
        Line(sb, "# Review each one, set its label (our-bug | checker-limitation | version-difference | severity-policy;");
        Line(sb, "# replace TODO) and confirmed: true, then copy it into the committed triage file in curated/comparison/.");
        Line(sb, "# Book or synthetic strings only (decision T-048).");
        Line(sb, "format: " + TriageFile.Format);
        Line(sb, "version: " + TriageFile.Version.ToString(CultureInfo.InvariantCulture));
        Line(sb, "checker: " + Yaml.Quote(result.Checker));
        Line(sb, "edition: " + Yaml.Quote(result.Edition));
        var untriaged = result.Items
            .Where(i => i.IsDisagreement && i.Triage is null)
            .DistinctBy(i => i.Item.Input, StringComparer.Ordinal)
            .ToList();
        if (untriaged.Count == 0)
        {
            Line(sb, "entries: []");
            return sb.ToString();
        }

        Line(sb, "entries:");
        foreach (var i in untriaged)
        {
            var note = i.Agreement == Agreement.OnlyCytoLexInvalid
                ? $"CytoLex: {string.Join(", ", i.CytoLexErrors)}"
                : $"{result.Checker}: {i.External.ToolStatus}"
                    + (i.External.Messages.FirstOrDefault() is { } msg ? " — " + Shorten(msg.Text) : "")
                    + (i.CytoLexNotes.IsEmpty ? "" : $"; CytoLex warnings/infos: {string.Join(", ", i.CytoLexNotes)}");
            var label = i.SuggestedLabel is { } s ? TriageFile.LabelName(s) : "TODO";
            TriageFile.AppendEntry(sb, i.Item.Input, label, false, note, null, null);
        }

        return sb.ToString();
    }

    /// <summary>
    /// The confirmed triage entries with <c>expected</c> and <c>kb_rule</c>, grouped by rule as KB <c>examples</c> lists,
    /// to paste into <c>curated/rules/</c> by hand with a citation (nothing edits the KB automatically).
    /// </summary>
    public static string KbExampleDraft(TriageFile triage)
    {
        ArgumentNullException.ThrowIfNull(triage);
        var sb = new StringBuilder();
        Line(sb, "# Draft KB examples from the confirmed triage entries (T-051), grouped by rule.");
        Line(sb, $"# Paste each example into its rule's examples in curated/rules/{triage.Edition}/, replace cite: TODO with the");
        Line(sb, "# book citation (or drop the example if the book has no basis), then run `kb check` and `kb build`.");
        var byRule = triage.Entries
            .Where(e => e.Confirmed && e.Expected is not null && e.KbRule is not null)
            .GroupBy(e => e.KbRule!, StringComparer.Ordinal)
            .OrderBy(g => g.Key, StringComparer.Ordinal)
            .ToList();
        if (byRule.Count == 0)
        {
            Line(sb, "{}");
            return sb.ToString();
        }

        foreach (var rule in byRule)
        {
            Line(sb, rule.Key + ":");
            foreach (var kind in new[] { ExpectedVerdict.Valid, ExpectedVerdict.Invalid })
            {
                var examples = rule.Where(e => e.Expected == kind).ToList();
                if (examples.Count == 0)
                {
                    continue;
                }

                Line(sb, kind == ExpectedVerdict.Valid ? "  valid:" : "  invalid:");
                foreach (var e in examples)
                {
                    Line(sb, "    - text: " + Yaml.Quote(e.Iscn));
                    Line(sb, "      cite: TODO");
                    Line(sb, $"      note: {Yaml.Quote($"{TriageFile.LabelName(e.Label)} ({triage.Checker} comparison)" + (e.Note is null ? "" : ": " + e.Note))}");
                }
            }
        }

        return sb.ToString();
    }

    /// <summary>The CSV name of an agreement.</summary>
    public static string AgreementName(Agreement agreement) => agreement switch
    {
        Agreement.BothValid => "both-valid",
        Agreement.BothInvalid => "both-invalid",
        Agreement.OnlyCytoLexInvalid => "only-cytolex-invalid",
        Agreement.OnlyCheckerInvalid => "only-checker-invalid",
        Agreement.NotSupported => "not-supported",
        Agreement.NotCompared => "not-compared",
        _ => throw new ArgumentOutOfRangeException(nameof(agreement)),
    };

    private static string StatusText(ComparisonResult result) => result.CheckerStatus switch
    {
        ExternalBatchStatus.Completed => "ran",
        ExternalBatchStatus.NotConfigured => "not configured: " + result.CheckerMessage,
        _ => "failed: " + result.CheckerMessage,
    };

    private static string TriageText(ComparisonItem i) => i.Triage is { } t
        ? TriageFile.LabelName(t.Label) + (t.Confirmed ? "" : " (unconfirmed)")
        : i.SuggestedLabel is { } s ? TriageFile.LabelName(s) + " (suggested)" : "–";

    private static string Percent(int part, int whole) =>
        whole == 0 ? "–" : (100.0 * part / whole).ToString("0.0", CultureInfo.InvariantCulture) + " %";

    private static string Shorten(string text)
    {
        var oneLine = text.ReplaceLineEndings(" ").Trim();
        return oneLine.Length <= 120 ? oneLine : oneLine[..117] + "…";
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);

    private static string Code(string text) => "`" + Cell(text).Replace("`", "'", StringComparison.Ordinal) + "`";

    private static string Bool(bool value) => value ? "true" : "false";

    private static void Line(StringBuilder sb, string text = "") => sb.Append(text).Append('\n');

    private static void CsvRow(StringBuilder sb, IEnumerable<string> fields)
    {
        sb.Append(string.Join(',', fields.Select(CsvField))).Append('\n');
    }

    private static string CsvField(string value) =>
        value.AsSpan().IndexOfAny(",\"\n\r") >= 0 ? "\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"" : value;
}
