"""`build/review/associations-review.md` (T-108): the association rules in plain words.

Written for reviewers who don't read YAML: one paragraph per rule saying which condition is shown
for which abnormalities, with context, strength, source and review state. Unreviewed rules first.
"""

from .check import CheckResult

SYMBOLS = {
    "t": "the translocation",
    "inv": "the inversion",
    "del": "the deletion",
    "dup": "the duplication",
    "i": "the isochromosome",
    "idic": "the isodicentric chromosome",
    "der": "the derivative chromosome",
    "ins": "the insertion",
    "r": "the ring chromosome",
    "dic": "the dicentric chromosome",
    "trp": "the triplication",
    "add": "additional material of unknown origin at",
}
SYSTEMS = {"orphanet": "", "icd10": "ICD-10 ", "icdo3": "ICD-O-3 ", "mondo": "", "other": ""}


def _fmt(n: int) -> str:
    return f"{n:,}"


def _exact(form: str) -> str:
    if form[0] == "+":
        return f"an extra chromosome {form[1:]} ({form})"
    if form[0] == "-":
        return f"a missing chromosome {form[1:]} ({form})"
    sym = form.split("(", 1)[0]
    return f"{SYMBOLS.get(sym, 'the abnormality')} {form}"


def describe(node: dict) -> str:
    """One match node in plain words."""
    ((key, value),) = node.items()
    if key == "exact":
        return _exact(value)
    if key == "fusion":
        return f"any rearrangement that joins band {value[0]} and band {value[1]}"
    if key == "copy":
        start, end = value["grch38"]
        band = f", band {value['band']}" if value.get("band") else ""
        return (
            f"a {value['effect']} overlapping chr{value['chrom']}:{_fmt(start)}–{_fmt(end)} "
            f"(GRCh38{band})"
        )
    if key == "not":
        return f"not {describe(value)}"
    parts = [describe(c) for c in value]
    if len(parts) == 1:
        return parts[0]
    if key == "any":
        return ", or ".join(parts)
    return "all of: " + "; ".join(parts)


def _condition(rule: dict) -> str:
    c = rule["condition"]
    ids = ", ".join(f"{SYSTEMS[i['system']]}{i['code']}" for i in c.get("ids", []))
    return f"**{c['name']}**" + (f" ({ids})" if ids else "")


def _paragraph(rule: dict, conflicts: list[str]) -> list[str]:
    rv = rule["review"]
    lines = [
        f"- `{rule['id']}` — {_condition(rule)}: {rule['context']} context, {rule['strength']}.",
        f"  Shown when the result has {describe(rule['match'])}.",
        f"  Source ({rule['source']}): {rule['citation']}.",
    ]
    for d in rule.get("defining", []):
        lines.append(f"  Defining criterion in {d['source']}: {d['citation']}.")
    if rv["reviewed"]:
        lines.append(f"  Reviewed by {rv['reviewer']} on {rv['date']}.")
    if rv.get("note"):
        lines.append(f"  Note: {rv['note']}")
    lines += [f"  **Conflict:** {m}" for m in conflicts]
    return lines


def review_markdown(rules: list[dict], result: CheckResult) -> str:
    unreviewed = [r for r in rules if not r["review"]["reviewed"]]
    reviewed = [r for r in rules if r["review"]["reviewed"]]
    by_rule: dict[str, list[str]] = {}
    for c in result.conflicts:
        by_rule.setdefault(c.rule["id"], []).append(c.message)
    lines = [
        "# Association rules review",
        "",
        "Generated by `kb build` from `curated/associations/associations.yaml`; do not edit. How "
        "to edit the rules: `curated/associations/README.md`.",
        "",
        "These are conditions associated in the literature, shown next to a result; they are "
        "not a diagnosis or an interpretation of the result.",
        "",
        f"{len(rules)} rules · {len(reviewed)} reviewed · {len(unreviewed)} not reviewed · "
        f"{len(result.conflicts)} conflict(s)",
        "",
    ]
    for title, group in (("Not reviewed", unreviewed), ("Reviewed", reviewed)):
        lines += [f"## {title} ({len(group)})", ""]
        for r in group:
            lines += _paragraph(r, by_rule.get(r["id"], []))
        if not group:
            lines.append("None.")
        lines.append("")
    return "\n".join(lines)
