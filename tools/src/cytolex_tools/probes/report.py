"""`build/review/probes-review.md` (T-102): what in the probe table still needs a person."""

from .check import CheckResult
from .names import placed_by_name
from .table import Table


def review_markdown(tab: Table, result: CheckResult, example_names: set[str]) -> str:
    rows = tab.rows
    unreviewed = [r for r in rows if not r.reviewed]
    known = {n.casefold() for r in rows for n in (r.name, *r.aliases)}
    missing = sorted(n for n in example_names if n.casefold() not in known)
    by_name = [n for n in missing if placed_by_name(n)]
    need_row = [n for n in missing if not placed_by_name(n)]
    lines = [
        "# Probe table review",
        "",
        "Generated by `kb build` from `curated/probes/probes.csv`; do not edit. How to edit the "
        "table: `curated/probes/README.md`.",
        "",
        f"{len(rows)} rows · {len(rows) - len(unreviewed)} reviewed · {len(unreviewed)} not "
        f"reviewed · {len(result.conflicts)} conflict(s)",
        "",
        f"## Conflicts ({len(result.conflicts)})",
        "",
    ]
    lines += [f"- {c.row.where()} [{c.kind}]: {c.message}" for c in result.conflicts] or ["None."]
    lines += ["", f"## Not reviewed ({len(unreviewed)})", ""]
    lines += [f"- {r.where()} {r['band'] or '(no band)'}: {r['source']}" for r in unreviewed]
    if not unreviewed:
        lines.append("None.")
    lines += [
        "",
        f"## Probe names in the KB examples without a row ({len(need_row)})",
        "",
        "Clones, vendor probes and regions need a row typed in from a cited source "
        "(datasheet, NCBI Clone DB, …); gene symbols can be added with `kb probes --add`.",
        "",
    ]
    lines += [f"- `{n}`" for n in need_row] or ["None."]
    lines += [
        "",
        f"## Placed by name, no row needed ({len(by_name)})",
        "",
        "D-numbers name their chromosome (T-101); a row would add the band and positions.",
        "",
    ]
    lines += [f"- `{n}`" for n in by_name] or ["None."]
    return "\n".join(lines) + "\n"
